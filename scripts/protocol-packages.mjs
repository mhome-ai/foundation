export function protocolPackage(name) {
  const config = PROTOCOL_PACKAGES[name];
  if (!config) {
    throw new Error(
      `Unknown protocol package ${JSON.stringify(name)}; expected one of ${Object.keys(
        PROTOCOL_PACKAGES
      ).join(", ")}`
    );
  }
  return config;
}
